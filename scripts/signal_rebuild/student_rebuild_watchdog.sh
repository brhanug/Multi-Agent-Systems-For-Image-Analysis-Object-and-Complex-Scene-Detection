#!/usr/bin/env bash
# Keeps the student rebuild going after the Claude session ends, then scores the result.
#
#   setsid nohup bash scripts/signal_rebuild/student_rebuild_watchdog.sh <training pid> >/dev/null 2>&1 < /dev/null &
#
# 1. Waits while the given training process runs.
# 2. If training stopped before finishing (the session ended, the machine rebooted, the process was
#    killed), resumes from the last checkpoint, up to 5 times. Ultralytics marks a finished run by
#    setting epoch = -1 in last.pt; anything else means unfinished.
# 3. When training is finished, scores the new student on the 300 hand-annotated pictures with the same
#    AP50 routine as the candidate teachers, and writes REBUILD_DONE.
#
# Progress: results/signal_rebuild/student_rebuild/watchdog.log
# Do NOT edit this file while it is running.
set -u
BASE=/data/brhanu/thesis_project
PY=$BASE/.venv/bin/python3
RUN=$BASE/runs/detect/yolo11_gdino_consensus
OUT=$BASE/results/signal_rebuild/student_rebuild
LOG=$OUT/watchdog.log
TRAIN_PID=${1:-}
cd "$BASE"

say() { echo "[$(date '+%F %T')] $*" >> "$LOG"; }
finished() {
  [ -f "$RUN/weights/last.pt" ] || return 1
  "$PY" -c "import torch, sys; ck = torch.load('$RUN/weights/last.pt', map_location='cpu', weights_only=False); sys.exit(0 if ck.get('epoch', 0) == -1 else 1)" 2>/dev/null
}

say "watchdog started (pid $$), watching training pid ${TRAIN_PID:-none}"
if [ -n "$TRAIN_PID" ]; then
  while kill -0 "$TRAIN_PID" 2>/dev/null; do sleep 60; done
  say "training process $TRAIN_PID has exited"
fi

tries=0
until finished; do
  tries=$((tries + 1))
  if [ "$tries" -gt 5 ]; then say "still unfinished after 5 resumes; stopping"; exit 1; fi
  if [ -f "$RUN/weights/last.pt" ]; then
    say "training unfinished; resuming from last.pt (attempt $tries)"
    "$PY" -c "from ultralytics import YOLO; YOLO('$RUN/weights/last.pt').train(resume=True)" >> "$LOG" 2>&1
  else
    say "no checkpoint; starting training from scratch (attempt $tries)"
    "$PY" scripts/signal_rebuild/train_gdino_student.py --device 1 >> "$LOG" 2>&1
  fi
done

say "training finished; scoring the new student on the 300 hand-annotated pictures"
if CUDA_VISIBLE_DEVICES=1 "$PY" scripts/signal_rebuild/run_teacher_candidates_on_300.py >> "$LOG" 2>&1; then
  say "evaluation written to $OUT/teacher_candidates_300.json"
  touch "$OUT/REBUILD_DONE"
else
  say "evaluation FAILED; see the lines above"
fi
